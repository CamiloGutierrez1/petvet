-- Una fila por correo enviado. message_id es la propiedad AMQP messageId del mensaje de Citas
-- (el UUID de su outbox) y es la clave de deduplicación: la entrega es al menos una vez y el mismo
-- mensaje nunca genera dos correos. Es texto y no UUID para aceptar mensajes publicados a mano.
-- La fila se inserta en la misma transacción que envía el correo: si el envío falla, desaparece.
CREATE TABLE notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id VARCHAR(255) NOT NULL UNIQUE,
    tipo VARCHAR(32) NOT NULL,
    destino TEXT NOT NULL,
    asunto TEXT NOT NULL,
    cuerpo TEXT NOT NULL,
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    enviada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT notificaciones_tipo_valido CHECK (
        tipo IN ('CITA_AGENDADA', 'CITA_COMPLETADA', 'VACUNA_PROXIMA')
    )
);

CREATE INDEX notificaciones_enviada_idx ON notificaciones (enviada_en DESC, id DESC);
