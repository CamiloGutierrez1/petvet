CREATE TABLE veterinarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    especialidad VARCHAR(255) NOT NULL
);

CREATE TABLE citas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mascota_id BIGINT NOT NULL,
    veterinario_id BIGINT NOT NULL REFERENCES veterinarios (id),
    fecha_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    tipo_servicio VARCHAR(32) NOT NULL,
    estado VARCHAR(16) NOT NULL,
    CONSTRAINT citas_tipo_servicio_valido CHECK (
        tipo_servicio IN ('CONSULTA_GENERAL', 'VACUNACION', 'CONTROL', 'ESPECIALISTA')
    ),
    CONSTRAINT citas_estado_valido CHECK (
        estado IN ('AGENDADA', 'COMPLETADA', 'CANCELADA')
    )
);

CREATE UNIQUE INDEX citas_veterinario_horario_unico
    ON citas (veterinario_id, fecha_hora)
    WHERE estado <> 'CANCELADA';

CREATE UNIQUE INDEX citas_mascota_horario_unico
    ON citas (mascota_id, fecha_hora)
    WHERE estado <> 'CANCELADA';

CREATE INDEX citas_mascota_fecha_idx ON citas (mascota_id, fecha_hora);
CREATE INDEX citas_veterinario_fecha_idx ON citas (veterinario_id, fecha_hora);

CREATE TABLE registros_historial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id BIGINT NOT NULL UNIQUE REFERENCES citas (id),
    mascota_id BIGINT NOT NULL,
    veterinario_id BIGINT NOT NULL REFERENCES veterinarios (id),
    fecha TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    tipo_consulta VARCHAR(16) NOT NULL,
    diagnostico TEXT NOT NULL,
    observaciones TEXT,
    proximo_control DATE,
    CONSTRAINT historial_tipo_consulta_valido CHECK (
        tipo_consulta IN ('GENERAL', 'ESPECIALISTA')
    )
);

CREATE INDEX historial_mascota_fecha_idx ON registros_historial (mascota_id, fecha);

CREATE TABLE historial_vacunas (
    historial_id BIGINT NOT NULL REFERENCES registros_historial (id) ON DELETE CASCADE,
    posicion INTEGER NOT NULL,
    valor TEXT NOT NULL,
    PRIMARY KEY (historial_id, posicion)
);

CREATE TABLE historial_tratamientos (
    historial_id BIGINT NOT NULL REFERENCES registros_historial (id) ON DELETE CASCADE,
    posicion INTEGER NOT NULL,
    valor TEXT NOT NULL,
    PRIMARY KEY (historial_id, posicion)
);

CREATE TABLE historial_examenes (
    historial_id BIGINT NOT NULL REFERENCES registros_historial (id) ON DELETE CASCADE,
    posicion INTEGER NOT NULL,
    valor TEXT NOT NULL,
    PRIMARY KEY (historial_id, posicion)
);

