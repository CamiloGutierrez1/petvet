CREATE TABLE duenos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    documento VARCHAR(30),
    -- Se guarda sin espacios y en minúsculas, así UNIQUE no distingue mayúsculas.
    email VARCHAR(254) NOT NULL,
    telefono VARCHAR(10),
    direccion VARCHAR(200),
    CONSTRAINT duenos_email_unico UNIQUE (email),
    CONSTRAINT duenos_telefono_valido CHECK (telefono ~ '^[0-9]{7,10}$')
);

CREATE TABLE mascotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL,
    especie VARCHAR(8) NOT NULL,
    raza VARCHAR(60) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    peso NUMERIC(6, 2) NOT NULL,
    -- Solo las fotos de ejemplo, relativas al front. Una foto subida nunca guarda aquí su URL.
    foto_url VARCHAR(255),
    dueno_id BIGINT NOT NULL REFERENCES duenos (id),
    CONSTRAINT mascotas_especie_valida CHECK (especie IN ('PERRO', 'GATO', 'AVE', 'OTRO')),
    CONSTRAINT mascotas_peso_positivo CHECK (peso > 0)
);

CREATE INDEX mascotas_dueno_idx ON mascotas (dueno_id);

